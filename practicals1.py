# Different data types
a = 10
b = 10.5
c = "Python"
d = True
e = [1, 2, 3, 4]

print("Integer:", a)
print("Float:", b)
print("String:", c)
print("Boolean:", d)
print("List:", e)

# Built-in functions
print("Length:", len(c))
print("Integer conversion:", int(b))
print("Maximum:", max(e))
print("Rounded value:", round(b))
print("String conversion:", str(a))
print("Type of a:", type(a))